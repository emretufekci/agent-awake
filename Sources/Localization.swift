func L(_ key: String, _ args: CVarArg...) -> String {
    let table = Loc.strings[Loc.active] ?? [:]
    let fmt = table[key] ?? Loc.strings[.en]?[key] ?? key
    return args.isEmpty ? fmt : String(format: fmt, locale: Loc.locale, arguments: args)
}
