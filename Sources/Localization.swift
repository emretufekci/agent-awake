enum Lang: String, CaseIterable {
    case system, en, tr

    /// Native name shown in the Language menu.
    var label: String {
        switch self {
        case .system: return L("systemDefault")
        case .en: return "English"
        case .tr: return "Türkçe"
        }
    }
}

